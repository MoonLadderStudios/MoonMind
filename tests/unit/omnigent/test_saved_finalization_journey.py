"""Save before owned cleanup, then finish from saved bytes (MoonMind#4016).

The generic realizer's own cleanup and finalization owners drive the real
workspace publication service and production artifact gateway (sqlite plus a
local blob volume). After the owned workspace is removed, finalization
restores the exact saved candidate from its checkpoint without a provider
driver, a host, or any repository credential, and resumes only the phase that
had not finished.
"""

